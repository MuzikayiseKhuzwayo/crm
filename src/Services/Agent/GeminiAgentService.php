<?php

namespace VentureDrake\LaravelCrm\Services\Agent;

use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;

class GeminiAgentService
{
    protected ?string $apiKey;

    protected string $model;

    protected CrmToolsService $tools;

    public function __construct(CrmToolsService $tools)
    {
        $this->apiKey = config('laravel-crm.agent.gemini_api_key');
        $this->model = config('laravel-crm.agent.gemini_model', 'gemini-2.5-flash');
        $this->tools = $tools;
    }

    /**
     * Run a conversational turn with Gemini and execute function calls.
     */
    public function executeTurn(string $prompt, array $history = []): string
    {
        if (! $this->apiKey) {
            return 'Gemini API key is not configured. Please set GEMINI_API_KEY in your .env file.';
        }

        $systemInstruction = $this->buildSystemInstruction();
        $toolDeclarations = $this->getToolDeclarations();

        $contents = $history;
        $contents[] = [
            'role' => 'user',
            'parts' => [
                ['text' => $prompt],
            ],
        ];

        $maxIterations = 5;
        $iteration = 0;

        while ($iteration < $maxIterations) {
            $iteration++;

            $payload = [
                'systemInstruction' => [
                    'parts' => [
                        ['text' => $systemInstruction],
                    ],
                ],
                'contents' => $contents,
                'tools' => [
                    [
                        'functionDeclarations' => $toolDeclarations,
                    ],
                ],
            ];

            $endpoint = "https://generativelanguage.googleapis.com/v1beta/models/{$this->model}:generateContent?key={$this->apiKey}";

            try {
                $response = Http::withoutVerifying()->timeout(30)->post($endpoint, $payload);
            } catch (\Throwable $e) {
                Log::error('Gemini request exception: '.$e->getMessage());

                return 'Error communicating with AI engine: '.$e->getMessage();
            }

            if (! $response->successful()) {
                Log::error('Gemini API error: '.$response->body());

                return "Gemini API error ({$response->status()}): ".$response->json('error.message', 'Unknown error');
            }

            $candidate = $response->json('candidates.0');
            if (! $candidate || ! isset($candidate['content'])) {
                return 'No response generated by AI model.';
            }

            $modelParts = $candidate['content']['parts'] ?? [];

            // Sanitize functionCall parts so empty args serialize as JSON object ({}) not array ([])
            foreach ($modelParts as &$part) {
                if (isset($part['functionCall'])) {
                    if (empty($part['functionCall']['args'])) {
                        $part['functionCall']['args'] = (object) [];
                    }
                }
            }
            unset($part);

            // Add model candidate to conversation history
            $contents[] = [
                'role' => 'model',
                'parts' => $modelParts,
            ];

            // Check if there are function calls to execute
            $functionCalls = [];
            foreach ($modelParts as $part) {
                if (isset($part['functionCall'])) {
                    $functionCalls[] = $part['functionCall'];
                }
            }

            if (empty($functionCalls)) {
                // Return final text response
                $textParts = [];
                foreach ($modelParts as $part) {
                    if (isset($part['text'])) {
                        $textParts[] = $part['text'];
                    }
                }

                return implode("\n\n", $textParts) ?: 'Action completed.';
            }

            // Execute each function call and append function responses
            foreach ($functionCalls as $fn) {
                $fnName = $fn['name'];
                $fnArgs = $fn['args'] ?? [];

                $executionResult = $this->dispatchTool($fnName, $fnArgs);

                $contents[] = [
                    'role' => 'function',
                    'parts' => [
                        [
                            'functionResponse' => [
                                'name' => $fnName,
                                'response' => (object) [
                                    'result' => $executionResult,
                                ],
                            ],
                        ],
                    ],
                ];
            }
        }

        return 'Maximum function execution turns reached.';
    }

    /**
     * Dispatch tool call to CrmToolsService.
     */
    protected function dispatchTool(string $name, array $args): mixed
    {
        try {
            return match ($name) {
                'get_crm_overview' => $this->tools->getCrmOverview(),
                'query_leads' => $this->tools->queryLeads($args),
                'get_lead_details' => $this->tools->getLeadDetails($args),
                'query_tasks' => $this->tools->queryTasks($args),
                'create_task' => $this->tools->createTask($args),
                'complete_task' => $this->tools->completeTask($args),
                'update_lead_stage' => $this->tools->updateLeadStage($args),
                'delete_lead' => $this->tools->deleteLead($args),
                'get_lead_alerts' => $this->tools->getLeadAlerts(),
                default => ['error' => "Unknown tool: {$name}"],
            };
        } catch (\Throwable $e) {
            Log::error("Error executing tool {$name}: ".$e->getMessage());

            return ['error' => $e->getMessage()];
        }
    }

    /**
     * Persona and directives (OpenClaw SOUL style).
     */
    protected function buildSystemInstruction(): string
    {
        return <<<'PROMPT'
You are the autonomous CRM Chief of Staff and Operator for Muzi Khuzwayo at Techfusion / Alchemy CRM.
Your job is to manage leads, monitor pipeline velocity, keep tasks on track, and proactively alert on anomalies.

DIRECTIVES & RULES:
1. Be concise, executive, and decisive. Avoid conversational fluff like "Certainly!" or "How can I help you today?".
2. You interact primarily via Telegram. Format messages using clean, readable Markdown (bullet points, bold headers, emoji accents). Avoid unescaped special characters that break markdown.
3. When asked to inspect or manage leads/tasks, always call the relevant CRM tools. Do not hallucinate CRM IDs or task states.
4. When reporting lead alerts or overdue tasks, provide the Lead ID (e.g. LD-1042), Person/Company name, and clear actionable recommendations.
5. If the user asks you to create a task, complete a task, or update a lead, execute the tool immediately and confirm with the updated status.
6. If the user explicitly asks to delete, remove, or drop a lead (or confirms deletion), invoke the delete_lead tool directly and report what was deleted.
PROMPT;
    }

